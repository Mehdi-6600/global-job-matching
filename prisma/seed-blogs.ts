async function main() {
  const admin = await prisma.user.findFirst({ where: { email: "admin@globaljobmatching.com" } });
  if (!admin) {
    console.error("Admin user not found - run seed.ts first");
    process.exit(1);
  }

  for (const post of posts) {
    await prisma.blogPost.upsert({
      where: { slug: post.slug },
      update: { ...post, authorId: admin.id },
      create: { ...post, authorId: admin.id },
    });
    console.log(`Upserted: ${post.slug}`);
  }
  console.log("Blog seed done");
}

main().catch((e) => { console.error(e); process.exit(1); }).finally(async () => prisma.$disconnect());
