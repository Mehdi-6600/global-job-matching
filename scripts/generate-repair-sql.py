#!/usr/bin/env python3
"""Regenerate the paste-ready repair SQL in docs/repair/.

Why this exists: production sat 18 migrations behind the Prisma schema, so
`/api/jobs` returned 500. The fix is to replay the pending (all idempotent)
migrations and then record them in `_prisma_migrations`, which is what
`prisma migrate resolve --applied` does — but that needs a Node toolchain, and
the person running it may only have a SQL editor.

Usage:
    python3 scripts/generate-repair-sql.py            # after the migration below
    python3 scripts/generate-repair-sql.py --after 20260902090000_production_baseline

Outputs:
    docs/repair/01-schema.sql              replay of the pending migrations
    docs/repair/02-migration-history.sql   bookkeeping inserts with SHA-256

Both are idempotent. Run 01, then 02.
"""
import argparse
import hashlib
import os

MIGRATIONS = os.path.join("prisma", "migrations")
DEFAULT_AFTER = "20260902090000_production_baseline"

HEADER_01 = """-- ============================================================================
-- 01 — schema repair (generated by scripts/generate-repair-sql.py)
--
-- RUN THIS FIRST, then 02-migration-history.sql.
--
-- Replays the pending Prisma migrations in order. Every statement is idempotent
-- (IF NOT EXISTS / guarded DO blocks), so re-running the file is safe.
--
-- It contains no DROP, DELETE or TRUNCATE of data. The `migrate diff` output
-- also proposed dropping columns and a table; those are old leftovers and are
-- deliberately excluded.
--
-- WHERE: the production Postgres SQL editor. Take a backup first if the
-- provider offers one.
-- ============================================================================
"""

HEADER_02 = """-- ============================================================================
-- 02 — align the Prisma migration history (generated by scripts/generate-repair-sql.py)
--
-- RUN AFTER 01-schema.sql SUCCEEDED.
--
-- Equivalent to `prisma migrate resolve --applied <name>` for each migration in
-- 01. checksum = SHA-256 of the migration file, exactly what Prisma stores, so
-- `prisma migrate status` / `migrate deploy` accept the history.
--
-- Idempotent: migrations that are already recorded are skipped.
-- ============================================================================

"""


def migrations_after(cutoff: str) -> list[str]:
    names = [
        d
        for d in os.listdir(MIGRATIONS)
        if os.path.isdir(os.path.join(MIGRATIONS, d)) and d > cutoff
    ]
    return sorted(names)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--after", default=DEFAULT_AFTER, help="last migration the database already has")
    args = ap.parse_args()

    names = migrations_after(args.after)
    if not names:
        raise SystemExit(f"no migrations after {args.after}")

    os.makedirs("docs/repair", exist_ok=True)

    parts = [HEADER_01]

    # Prelude: "JobSource" is referenced (unguarded CREATE INDEX) by migrations
    # in this range, but the production_baseline file does not create it. On a
    # database that never ran the original 2026-03 migration those indexes fail
    # and can abort the whole paste. Create the table first, idempotently.
    prelude_name = "20261020040000_add_job_source_table"
    prelude = os.path.join(MIGRATIONS, prelude_name, "migration.sql")
    if os.path.exists(prelude) and prelude_name in names:
        parts.append(
            f"\n-- {'=' * 74}\n-- prelude — {prelude_name}\n"
            f"-- {'=' * 74}\n"
            + open(prelude, encoding="utf-8").read().rstrip()
            + "\n"
        )

    for name in names:
        if name == prelude_name:
            continue
        path = os.path.join(MIGRATIONS, name, "migration.sql")
        body = open(path, encoding="utf-8").read().rstrip()
        parts.append(f"\n-- {'-' * 74}\n-- migration: {name}\n-- {'-' * 74}\n{body}\n")
    open("docs/repair/01-schema.sql", "w", encoding="utf-8").write("\n".join(parts))

    lines = [HEADER_02]
    for name in names:
        path = os.path.join(MIGRATIONS, name, "migration.sql")
        digest = hashlib.sha256(open(path, "rb").read()).hexdigest()
        quoted = "'" + name + "'"
        lines.append(
            'INSERT INTO "_prisma_migrations"\n'
            "  (id, checksum, finished_at, migration_name, logs, rolled_back_at, started_at, applied_steps_count)\n"
            f"SELECT md5(random()::text || clock_timestamp()::text), '{digest}', NOW(), {quoted}, NULL, NULL, NOW(), 1\n"
            f'WHERE NOT EXISTS (SELECT 1 FROM "_prisma_migrations" WHERE migration_name = {quoted});\n'
        )
    lines.append(
        "\n-- Expect one row per migration, all applied = true.\n"
        'SELECT migration_name, finished_at IS NOT NULL AS applied\n'
        'FROM "_prisma_migrations"\n'
        "ORDER BY migration_name;\n"
    )
    open("docs/repair/02-migration-history.sql", "w", encoding="utf-8").write("\n".join(lines))

    for name in ("docs/repair/01-schema.sql", "docs/repair/02-migration-history.sql"):
        print(f"wrote {name} ({os.path.getsize(name)} bytes)")
    print(f"migrations included: {len(names)}")


if __name__ == "__main__":
    main()
